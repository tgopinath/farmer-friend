// Pins one real photo per crop into images.js from iNaturalist (taxon default photo, licensed for reuse).
// Run again to refresh: node tools/fetch-images.mjs. A key in PIN keeps a hand-picked photo instead.
import { writeFileSync } from 'node:fs';
const TAXA = {
  rice: 'Oryza sativa', wheat: 'Triticum aestivum', maize: 'Zea mays', sorghum: 'Sorghum bicolor', bajra: 'Cenchrus americanus',
  ragi: 'Eleusine coracana', urad: 'Vigna mungo', moong: 'Vigna radiata', chickpea: 'Cicer arietinum', tur: 'Cajanus cajan',
  groundnut: 'Arachis hypogaea', mustard: 'Brassica juncea', sesame: 'Sesamum indicum', sunflower: 'Helianthus annuus',
  tomato: 'Solanum lycopersicum', brinjal: 'Solanum melongena', chilli: 'Capsicum annuum', onion: 'Allium cepa',
  okra: 'Abelmoschus esculentus', potato: 'Solanum tuberosum', cabbage: 'Brassica oleracea', carrot: 'Daucus carota',
  watermelon: 'Citrullus lanatus', banana: 'Musa acuminata', mango: 'Mangifera indica', papaya: 'Carica papaya',
  turmeric: 'Curcuma longa', coriander: 'Coriandrum sativum', cotton: 'Gossypium hirsutum', sugarcane: 'Saccharum officinarum',
};
// Hand-picked Commons photos where the iNaturalist default shows the wild plant, not the crop.
const commons = (f, w) => `https://upload.wikimedia.org/wikipedia/commons/thumb/${f}/${w}px-${f.split('/').pop()}`;
const PIN = {
  cabbage: { src: commons('6/6f/Cabbage_and_cross_section_on_white.jpg', 960), thumb: commons('6/6f/Cabbage_and_cross_section_on_white.jpg', 330), credit: '(c) fir0002, GFDL 1.2, Wikimedia Commons' },
  carrot: { src: commons('a/a2/Vegetable-Carrot-Bundle-wStalks.jpg', 960), thumb: commons('a/a2/Vegetable-Carrot-Bundle-wStalks.jpg', 330), credit: 'Evan-Amos, public domain, Wikimedia Commons' },
  onion: { src: commons('a/a2/Mixed_onions.jpg', 960), thumb: commons('a/a2/Mixed_onions.jpg', 330), credit: '(c) Colin, CC BY-SA 3.0, Wikimedia Commons' },
  tomato: { src: commons('8/89/Tomato_je.jpg', 960), thumb: commons('8/89/Tomato_je.jpg', 330), credit: '(c) Softeis, CC BY-SA 3.0, Wikimedia Commons' },
  okra: { src: commons('9/95/Hong_Kong_Okra_Aug_25_2012.JPG', 960), thumb: commons('9/95/Hong_Kong_Okra_Aug_25_2012.JPG', 330), credit: '(c) Earth100, CC BY-SA 3.0, Wikimedia Commons' },
};
const sleep = ms => new Promise(r => setTimeout(r, ms));
const out = {};
for (const [k, name] of Object.entries(TAXA)) {
  if (PIN[k]) { out[k] = PIN[k]; continue; }
  const r = await fetch('https://api.inaturalist.org/v1/taxa?per_page=1&q=' + encodeURIComponent(name), { headers: { 'User-Agent': 'FarmerFriend/1.0' } });
  const t = (await r.json()).results?.[0];
  const p = t?.default_photo;
  out[k] = p ? { src: p.medium_url.replace('/medium.', '/large.'), thumb: p.medium_url, credit: p.attribution } : null;
  console.log(k, t?.name, p ? 'ok' : 'none');
  await sleep(700);
}
writeFileSync(new URL('../images.js', import.meta.url), '// Generated by tools/fetch-images.mjs: one iNaturalist photo per crop.\nconst CROP_IMAGES = ' + JSON.stringify(out, null, 2) + ';\n');
