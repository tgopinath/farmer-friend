// Saves a 420px copy of every crop's main photo into img/crops/ and writes images-local.js,
// so crop grids load from this site (Wikimedia rate-limits bursts of hotlinked images).
// Credits stay in CROP_IMAGES. Run: node tools/local-thumbs.mjs  (skips files already saved)
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
const root = new URL('..', import.meta.url).pathname;
const more = readdirSync(root).filter(f => /^data-crops-more-\d+\.js$/.test(f)).sort();
globalThis.window = globalThis;
new Function(['images.js', 'data-crops.js', ...more, 'media-inputs.js'].map(f => readFileSync(root + f, 'utf8')).join('\n').replace(/^const (\w+) =/gm, 'globalThis.$1 ='))();
const sleep = ms => new Promise(r => setTimeout(r, ms));
const saved = {};
for (const c of CROPS) {
  const p = CROP_IMAGES[c.id], out = `img/crops/${c.id}.jpg`;
  if (!p) continue;
  if (!existsSync(root + out)) {
    let buf;
    for (let tries = 0; tries < 6 && !buf; tries++) {
      const r = await fetch(p.src || p.thumb, { headers: { 'User-Agent': 'FarmerFriend/1.0 (farm guide app)' } });
      if (r.ok) buf = Buffer.from(await r.arrayBuffer());
      else { console.log(c.id, r.status, 'retrying'); await sleep(4000 * (tries + 1)); }
    }
    if (!buf) { console.log(c.id, 'FAILED'); continue; }
    const tmp = root + out + '.src';
    writeFileSync(tmp, buf);
    execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '70', '--resampleWidth', '420', tmp, '--out', root + out], { stdio: 'pipe' });
    execFileSync('rm', [tmp]);
    await sleep(1200);
  }
  saved[c.id] = out;
}
// Main photo of each organic input (the card and page banner).
const savedInputs = {};
for (const [id, list] of Object.entries(globalThis.MEDIA_INPUTS || {})) {
  const p = list[0], out = `img/inputs/${id}.jpg`;
  if (!p) continue;
  if (!existsSync(root + out)) {
    let buf;
    for (let tries = 0; tries < 6 && !buf; tries++) {
      const r = await fetch(p.src || p.thumb, { headers: { 'User-Agent': 'FarmerFriend/1.0 (farm guide app)' } });
      if (r.ok) buf = Buffer.from(await r.arrayBuffer());
      else { console.log(id, r.status, 'retrying'); await sleep(4000 * (tries + 1)); }
    }
    if (!buf) { console.log(id, 'FAILED'); continue; }
    const tmp = root + out + '.src';
    writeFileSync(tmp, buf);
    execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '72', '--resampleWidth', '760', tmp, '--out', root + out], { stdio: 'pipe' });
    execFileSync('rm', [tmp]);
    await sleep(1500);
  }
  savedInputs[id] = out;
}
writeFileSync(root + 'images-local.js', '// Generated by tools/local-thumbs.mjs: crop grid photos served from this site.\n' +
  `Object.entries(${JSON.stringify(saved)}).forEach(([id, f]) => { if (CROP_IMAGES[id]) CROP_IMAGES[id].thumb = f; });\n` +
  `Object.entries(${JSON.stringify(savedInputs)}).forEach(([id, f]) => { const m = (window.MEDIA_INPUTS || {})[id]; if (m && m[0]) m[0].thumb = f; });\n`);
console.log('saved', Object.keys(saved).length, 'of', CROPS.length);
